"""Generate web/src/lib/composition-names.generated.ts from the names table.

The core's `composition_names_json()` is the source of the names a host shows
for a composition's record (forms, laws, color laws, roles, kinds, places);
the core test `composition_names::tests` keeps the shared fixture
server/tests/data/composition-names-v1.json equal to it. The web bundle ships
this snapshot of the fixture and looks names up synchronously; there is no
endpoint for the table. The web test composition-names.test.ts fails if the
checked-in module drifts from the fixture, and `--check` here does the same
without writing.

Run: python3 server/scripts/gen_composition_names_ts.py [--check]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

_REPO = Path(__file__).resolve().parents[2]
_FIXTURE = _REPO / "server" / "tests" / "data" / "composition-names-v1.json"
_OUTPUT = _REPO / "web" / "src" / "lib" / "composition-names.generated.ts"

_TYPES = """export type Bilingual = { ja: string; en: string };

export type CompositionNames = {
\tschema: string;
\tforms: { id: string; name: Bilingual; description: Bilingual }[];
\tlaws: { code: string; name: Bilingual; family: Bilingual; summary: Bilingual; main: boolean }[];
\tcolor_laws: { code: string; name: Bilingual; family: Bilingual }[];
\troles: { id: string; name: Bilingual }[];
\tkinds: { id: string; name: Bilingual }[];
\tat: { id: string; name: Bilingual }[];
\tplaces: { id: string; name: Bilingual }[];
};
"""


def _ts_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _ts_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return _ts_string(value)
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{key}: {_ts_value(item)}" for key, item in value.items()) + " }"
    raise TypeError(f"unexpected value in the names table: {value!r}")


def render_ts(table: dict[str, Any] | None = None) -> str:
    if table is None:
        table = json.loads(_FIXTURE.read_text(encoding="utf-8"))
    lines = [
        "// Generated by server/scripts/gen_composition_names_ts.py from",
        "// server/tests/data/composition-names-v1.json. Do not edit by hand.",
        _TYPES,
        "export const COMPOSITION_NAMES: CompositionNames = {",
    ]
    for key, value in table.items():
        if isinstance(value, list):
            lines.append(f"\t{key}: [")
            lines.extend(f"\t\t{_ts_value(entry)}," for entry in value)
            lines.append("\t],")
        else:
            lines.append(f"\t{key}: {_ts_value(value)},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    rendered = render_ts()
    if "--check" in argv:
        current = _OUTPUT.read_text(encoding="utf-8") if _OUTPUT.exists() else ""
        if current != rendered:
            print(f"{_OUTPUT} differs from {_FIXTURE}; run {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"{_OUTPUT.name} matches {_FIXTURE.name}")
        return 0
    _OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {_OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
