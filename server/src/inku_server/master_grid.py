"""演奏出力のマスター解像度。

SVG は拡大自由だが、書き出した数値そのものは固定小数である。したがって
この定数が実質的なマスター解像度になる。すべての数値出力をここで宣言した
一つのグリッドへ載せ、書き出し箇所ごとの桁の不揃いを作らない。

grid = 10 ** -MASTER_GRID_DECIMALS
     = 1000 単位キャンバスでキャンバス比 1e-9

下限側 (再現性): プラットフォーム間の libm 差は相対 2e-16。1000 単位の座標で
絶対 1e-13 に相当し、このグリッドより 4 桁下にある。よってどの OS で演奏しても
同じ文字列が出る。実測では小数 11 桁目から差が出始める。

上限側 (物理): 100m の壁へ引き伸ばしても刻みは 100nm。可視光の波長 (400-700nm)
より細かいので、描く手段の側が先に限界に達する。
"""

from __future__ import annotations

MASTER_GRID_DECIMALS = 6


def fmt(value: float) -> str:
    """マスターグリッドへ載せた数値表記。桁は常に固定し、末尾の 0 を詰めない。

    詰めないのは容量ではなく検査可能性のため。桁が固定なら成果物のどの数値も
    ``-?\\d+\\.\\d{6}`` に一致し、グリッドに載っていることを正規表現 1 本で
    機械検査できる。詰めてしまうと ``695.45787`` が 6 桁グリッドの産物なのか
    生の float なのかを出力から見分けられず、「丸めてから詰めた」という手順を
    信じる形になる (2026-07-24 作者裁定)。

    整数は整数のまま書かれる (キャンバス寸法・viewBox など)。グリッドは
    小数を持つ値に対する規定である。
    """
    text = f"{value:.{MASTER_GRID_DECIMALS}f}"
    # -0.000000 は 0.000000 と同じ値なので表記を一つに寄せる。
    return text[1:] if text.startswith("-") and float(text) == 0.0 else text
